#!/usr/bin/env node
// Generate src/morph-map.js from the ACTUAL morph target names inside
// assets/facecap.glb (mesh.extras.targetNames), so the ARKit -> facecap
// mapping is verified against the file, not guessed.
//
// Run: node tools/gen-morph-map.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const here = path.dirname(fileURLToPath(import.meta.url));
const glbPath = path.join(here, '..', 'assets', 'facecap.glb');
const outPath = path.join(here, '..', 'src', 'morph-map.js');

// Canonical ARKit 52 blendshape names (as emitted by NVIDIA Audio2Face and
// most lip-sync bridges, lowerCamelCase).
const ARKIT52 = [
  'browDownLeft', 'browDownRight', 'browInnerUp', 'browOuterUpLeft', 'browOuterUpRight',
  'cheekPuff', 'cheekSquintLeft', 'cheekSquintRight',
  'eyeBlinkLeft', 'eyeBlinkRight', 'eyeLookDownLeft', 'eyeLookDownRight',
  'eyeLookInLeft', 'eyeLookInRight', 'eyeLookOutLeft', 'eyeLookOutRight',
  'eyeLookUpLeft', 'eyeLookUpRight', 'eyeSquintLeft', 'eyeSquintRight',
  'eyeWideLeft', 'eyeWideRight',
  'jawForward', 'jawLeft', 'jawOpen', 'jawRight',
  'mouthClose', 'mouthDimpleLeft', 'mouthDimpleRight', 'mouthFrownLeft', 'mouthFrownRight',
  'mouthFunnel', 'mouthLeft', 'mouthLowerDownLeft', 'mouthLowerDownRight',
  'mouthPressLeft', 'mouthPressRight', 'mouthPucker', 'mouthRight',
  'mouthRollLower', 'mouthRollUpper', 'mouthShrugLower', 'mouthShrugUpper',
  'mouthSmileLeft', 'mouthSmileRight', 'mouthStretchLeft', 'mouthStretchRight',
  'mouthUpperUpLeft', 'mouthUpperUpRight',
  'noseSneerLeft', 'noseSneerRight', 'tongueOut',
];

// ---- read the GLB JSON chunk ----
const buf = readFileSync(glbPath);
const jsonLen = buf.readUInt32LE(12);
const gltf = JSON.parse(buf.subarray(20, 20 + jsonLen).toString('utf8'));

let targetNames = null;
for (const mesh of gltf.meshes || []) {
  const names = mesh?.extras?.targetNames;
  if (names && names.length) { targetNames = names; break; }
}
if (!targetNames) { console.error('no mesh.extras.targetNames found in GLB'); process.exit(1); }

// facecap naming: ..._L / ..._R suffix. ARKit naming: ...Left / ...Right.
function toArkit(facecapName) {
  return facecapName.replace(/_L$/, 'Left').replace(/_R$/, 'Right');
}
function norm(s) {
  // fold case and separators so bridge payloads (ARKit standard names) can be
  // matched robustly: mouthSmile_L / mouthSmileLeft / MouthSmileLeft all -> "mouthsmileleft"
  return s.replace(/[_\s-]/g, '').toLowerCase();
}

const map = {};        // arkitName -> facecapName
const index = {};      // facecapName -> morph index
const pairs = [];
targetNames.forEach((t, i) => {
  index[t] = i;
  pairs.push([toArkit(t), t]);
});

// verification: exactly one pair per canonical ARKit name, no extras
const got = new Map(pairs.map(([a, f]) => [a, f]));
const missing = ARKIT52.filter(a => !got.has(a));
const extra = [...got.keys()].filter(a => !ARKIT52.includes(a));
if (targetNames.length !== 52) { console.error(`expected 52 targets, got ${targetNames.length}`); process.exit(1); }
if (missing.length || extra.length) {
  console.error('MISMATCH', { missing, extra }); process.exit(1);
}
const dup = pairs.length !== new Set(pairs.map(p => p[0])).size || pairs.length !== new Set(pairs.map(p => p[1])).size;
if (dup) { console.error('duplicate names'); process.exit(1); }

const src = `// GENERATED by tools/gen-morph-map.mjs from assets/facecap.glb mesh.extras.targetNames
// — verified 1:1 against the canonical ARKit 52 list (${pairs.length} pairs). Do not hand-edit; re-run the tool.

// ARKit standard name -> facecap morph target name
export const ARKIT_TO_FACECAP = {
${pairs.map(([a, f]) => `  ${JSON.stringify(a)}: ${JSON.stringify(f)},`).join('\n')}
};

// facecap morph target name -> index into morphTargetInfluences (GLB order)
export const FACECAP_INDEX = {
${targetNames.map((t, i) => `  ${JSON.stringify(t)}: ${i},`).join('\n')}
};

export const FACECAP_TARGETS = ${JSON.stringify(targetNames)};

// normalized lookup key (folds case + underscores): lets the bridge accept
// "MouthSmileLeft", "mouthSmileLeft" or "mouthSmile_Left" style names.
export function normKey(s) {
  return s.replace(/[_\\s-]/g, '').toLowerCase();
}

// normalized-name -> facecap target name (covers ARKit names, facecap names,
// and any case/underscore variant of either)
export const NORM_TO_FACECAP = {
${pairs.flatMap(([a, f]) => [
  `  ${JSON.stringify(norm(a))}: ${JSON.stringify(f)},`,
  `  ${JSON.stringify(norm(f))}: ${JSON.stringify(f)},`,
]).join('\n')}
};

export const MORPH_COUNT = ${targetNames.length};
`;
writeFileSync(outPath, src);
console.log(`OK: wrote ${path.relative(here, outPath)} with ${pairs.length} verified pairs`);
for (const [a, f] of pairs.slice(0, 5)) console.log('  e.g.', a, '->', f);
